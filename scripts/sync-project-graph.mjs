// scripts/sync-project-graph.mjs
//
// Auto-generate the dependency-graph section of docs/architecture/project-graph.md
// from real `workspace:*` edges in every apps/*/package.json and packages/*/package.json.
//
// Why: a hand-written Mermaid graph drifts the moment a package is added or a
// workspace dependency changes. The graph is the blast-radius reference used by
// agents and engineers; if it lies, cross-package changes get under-scoped.
//
// Modes:
//   node scripts/sync-project-graph.mjs          -> rewrite file if drifted (used by a "sync" script)
//   node scripts/sync-project-graph.mjs --check  -> verify only, exit 1 if drifted (used by ai:check)
//
// The generated Mermaid block lives between sentinel comments; prose around it
// (foundational blocks, bottlenecks, workflow) is preserved untouched.
//
// Determinism: edges are sorted, node labels are stable. Re-running on an
// unchanged repo produces no diff.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const GRAPH_DOC = path.join(ROOT, 'docs', 'architecture', 'project-graph.md');
const BEGIN = '<!-- BEGIN:auto-generated-graph -->';
const END = '<!-- END:auto-generated-graph -->';

const CHECK_MODE = process.argv.slice(2).includes('--check');

function readPackageJson(rel) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) return null;
  return JSON.parse(fs.readFileSync(abs, 'utf8'));
}

// Discover every workspace package by name -> { dir, name }.
function discoverPackages() {
  const out = new Map(); // pkgName -> { dir, name }
  for (const root of ['apps', 'packages']) {
    const dir = path.join(ROOT, root);
    if (!fs.existsSync(dir)) continue;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const rel = `${root}/${entry.name}`;
      const pj = readPackageJson(`${rel}/package.json`);
      if (!pj || !pj.name) continue;
      out.set(pj.name, { dir: rel, name: pj.name });
    }
  }
  return out;
}

// Extract workspace:* edges. Returns [{ from, to }] with absolute package names.
function extractEdges(packages) {
  const edges = [];
  for (const [name, { dir }] of packages) {
    const pj = readPackageJson(`${dir}/package.json`);
    if (!pj) continue;
    const deps = { ...pj.dependencies, ...pj.devDependencies, ...pj.peerDependencies };
    for (const [depName, spec] of Object.entries(deps)) {
      if (typeof spec !== 'string') continue;
      if (!spec.startsWith('workspace:')) continue;
      if (!packages.has(depName)) continue; // external or non-workspace dep
      edges.push({ from: name, to: depName });
    }
  }
  // Dedupe + sort for determinism.
  const seen = new Set();
  return edges
    .filter(({ from, to }) => {
      const key = `${from}->${to}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .sort((a, b) => (a.from + a.to).localeCompare(b.from + b.to));
}

// Stable Mermaid node id from a package name: @pumni/ui -> UI, apps/web kept as Web.
function nodeId(name) {
  if (name === 'web') return 'Web';
  const short = name.replace(/^@pumni\//, '');
  return short.replace(/(?:^|\b|[-_])([a-z])/g, (_, c) => c.toUpperCase()).replace(/[-_]/g, '');
}

function renderMermaid(edges, packages) {
  const lines = ['```mermaid', 'graph TD'];
  // Declare all nodes explicitly so isolated (leaf) packages still appear.
  for (const name of [...packages.keys()].sort()) {
    const id = nodeId(name);
    const label = name === 'web' ? 'apps/web' : name;
    lines.push(`  ${id}[${label}]`);
  }
  for (const { from, to } of edges) {
    lines.push(`  ${nodeId(from)} --> ${nodeId(to)}`);
  }
  lines.push('```');
  return lines.join('\n');
}

function buildGeneratedBlock(mermaid) {
  return [
    BEGIN,
    '// This block is auto-generated by scripts/sync-project-graph.mjs.',
    '// Do not edit by hand — run `bun run ai:graph:sync` to regenerate.',
    '// Prose sections below this block are human-authored and preserved.',
    '',
    mermaid,
    '',
    END,
  ].join('\n');
}

function readDoc() {
  if (!fs.existsSync(GRAPH_DOC)) {
    return { existed: false, content: '' };
  }
  return { existed: true, content: fs.readFileSync(GRAPH_DOC, 'utf8') };
}

function replaceOrAppendGraph(content, block) {
  const beginIdx = content.indexOf(BEGIN);
  const endIdx = content.indexOf(END);
  if (beginIdx >= 0 && endIdx > beginIdx) {
    // Replace existing block (include the trailing newline after END if present).
    const before = content.slice(0, beginIdx);
    const after = content.slice(endIdx + END.length).replace(/^\r?\n/, '');
    return `${before}${block}\n${after}`;
  }
  // No existing block: append after the first H2 "## Edges" section if present,
  // otherwise append at end. We expect the doc to have an "## Edges" heading.
  const edgesHeader = content.match(/^## Edges\s*$/m);
  if (edgesHeader) {
    const insertAt = edgesHeader.index + edgesHeader[0].length + 1; // after header + newline
    return `${content.slice(0, insertAt)}\n${block}\n\n${content.slice(insertAt)}`;
  }
  return `${content.trimEnd()}\n\n${block}\n`;
}

function main() {
  const packages = discoverPackages();
  if (packages.size === 0) {
    console.error('[sync-project-graph] No workspace packages found.');
    process.exit(1);
  }
  const edges = extractEdges(packages);
  const mermaid = renderMermaid(edges, packages);
  const generatedBlock = buildGeneratedBlock(mermaid);

  const { existed, content } = readDoc();
  if (!existed) {
    console.error(`[sync-project-graph] ${path.relative(ROOT, GRAPH_DOC)} not found.`);
    process.exit(1);
  }

  const hasBlock = content.includes(BEGIN) && content.includes(END);
  const upToDate = hasBlock && content.includes(generatedBlock);

  if (CHECK_MODE) {
    if (!hasBlock) {
      console.error(
        `[sync-project-graph] Missing ${BEGIN} ... ${END} block in docs/architecture/project-graph.md.`,
      );
      console.error('  Run `bun run ai:graph:sync` to insert it.');
      process.exit(1);
    }
    if (!upToDate) {
      console.error(
        '[sync-project-graph] docs/architecture/project-graph.md graph is out of sync with workspace:* edges.',
      );
      console.error('  Run `bun run ai:graph:sync` and commit the result.');
      process.exit(1);
    }
    console.log('[sync-project-graph] Graph in sync.');
    return;
  }

  if (upToDate) {
    console.log('[sync-project-graph] Already in sync; no changes.');
    return;
  }

  const next = replaceOrAppendGraph(content, generatedBlock);
  fs.writeFileSync(GRAPH_DOC, next, 'utf8');
  console.log('[sync-project-graph] Updated docs/architecture/project-graph.md.');
}

main();
