/**
 * sync-nav-table — generate the AGENTS.md navigation table from context-map.json
 *
 *   bun scripts/sync-nav-table.mjs           # write/refresh table
 *   bun scripts/sync-nav-table.mjs --check   # check only
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const AGENTS_MD = path.join(ROOT, 'AGENTS.md');
const MAP_PATH = path.join(ROOT, 'scripts', 'context-scope-map.json');

const BEGIN = '<!-- BEGIN:auto-generated-nav -->';
const END = '<!-- END:auto-generated-nav -->';

const checkOnly = process.argv.includes('--check');

function main() {
  if (!fs.existsSync(MAP_PATH)) {
    console.error(`[sync-nav-table] Missing ${MAP_PATH}`);
    process.exit(1);
  }
  const { scopes } = JSON.parse(fs.readFileSync(MAP_PATH, 'utf8'));

  const rows = [];
  rows.push('| Editing… | Read first | Relevant skill |');
  rows.push('|---|---|---|');

  for (const sub of scopes) {
    if (!sub.nav) continue;
    const navs = Array.isArray(sub.nav) ? sub.nav : [sub.nav];
    for (const nav of navs) {
      const readFirst = nav.read_first;
      const skill = nav.skill && nav.skill !== '—' ? `\`${nav.skill}\`` : '—';
      rows.push(`| ${nav.editing} | ${readFirst} | ${skill} |`);
    }
  }

  const generated = [
    BEGIN,
    '// This block is auto-generated by scripts/sync-nav-table.mjs.',
    '// Do not edit by hand — run `bun run ai:nav:sync` to regenerate.',
    '// Prose sections below this block are human-authored and preserved.',
    '',
    ...rows,
    '',
    END
  ].join('\n');

  if (!fs.existsSync(AGENTS_MD)) {
    console.error(`[sync-nav-table] Missing ${AGENTS_MD}`);
    process.exit(1);
  }

  const content = fs.readFileSync(AGENTS_MD, 'utf8');
  const beginIdx = content.indexOf(BEGIN);
  const endIdx = content.indexOf(END);

  const hasBlock = beginIdx >= 0 && endIdx > beginIdx;
  const upToDate = hasBlock && content.includes(generated);

  if (checkOnly) {
    if (!upToDate) {
      console.error('[sync-nav-table] Navigation table in AGENTS.md is out of sync.');
      console.error('  Run `bun run ai:nav:sync` and commit the result.');
      process.exit(1);
    }
    console.log('[sync-nav-table] Navigation table in sync.');
    return;
  }

  if (upToDate) {
    console.log('[sync-nav-table] Navigation table already in sync.');
    return;
  }

  let next;
  if (hasBlock) {
    const before = content.slice(0, beginIdx);
    const after = content.slice(endIdx + END.length).replace(/^\r?\n/, '');
    next = `${before}${generated}\n${after}`;
  } else {
    // Replace the raw markdown table
    const tableHeader = '| Editing… | Read first | Relevant skill |';
    const tableHeaderIdx = content.indexOf(tableHeader);
    if (tableHeaderIdx === -1) {
      console.error('[sync-nav-table] Cannot find navigation table in AGENTS.md to insert markers.');
      process.exit(1);
    }
    const beforeTable = content.slice(0, tableHeaderIdx);
    const linesAfter = content.slice(tableHeaderIdx).split('\n');
    let endOfTableOffset = tableHeaderIdx;
    for (const line of linesAfter) {
      if (line.trim().startsWith('|')) {
        endOfTableOffset += line.length + 1;
      } else {
        break;
      }
    }
    const afterTable = content.slice(endOfTableOffset).replace(/^\r?\n/, '');
    next = `${beforeTable}${generated}\n${afterTable}`;
  }

  fs.writeFileSync(AGENTS_MD, next, 'utf8');
  console.log('[sync-nav-table] Updated AGENTS.md navigation table.');
}

main();
